//! # particlecode-ffi
//!
//! The Rust side of the Flutter plugin (`flutter/particle_code`), bridged with
//! `flutter_rust_bridge` v2. All logic lives in `particlecode-core` and
//! `particlecode-vision`; this crate only reshapes it into types that cross the Dart
//! boundary cheaply.
//!
//! * [`api`]: opaque handles with methods ([`api::encoder::ParticleEncoder`],
//!   [`api::decoder::ParticleDecoder`]) and plain DTOs. `flutter_rust_bridge_codegen
//!   generate` (configured by `flutter/particle_code/flutter_rust_bridge.yaml`) reads this
//!   module and writes the Dart bindings plus `frb_generated.rs` here.
//! * [`json`]: the serde JSON form of a [`FrameSpec`](particlecode_core::FrameSpec), for
//!   debugging and painters that prefer to parse text.
//!
//! The crate builds as a `cdylib` that the plugin's Native Assets build hook
//! (`flutter/particle_code/hook/build.dart`) compiles and bundles for each target. The
//! README next to `Cargo.toml` documents the painter contract (coordinates, colors, draw
//! order, timers).
//!
//! # Camera input
//!
//! [`api::decoder::ParticleDecoder`] takes camera frames and runs `particlecode_vision`
//! (locate, read) before feeding the receiver:
//!
//! * `feed_camera_frame` reads Android `YUV_420_888` / iOS NV12 planes **in place**, by
//!   address. The plugin's native camera code holds the frame until Dart releases it, after
//!   the call returns. The only `unsafe` in the crate (outside generated code) is there.
//! * `feed_yuv` and `feed_rgba` take owned buffers (tests, desktop, stills).
//! * `feed_symbols` accepts symbols classified elsewhere.

